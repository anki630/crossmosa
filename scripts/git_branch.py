"""
PlatformIO pre-build script: write CROSSPOINT_VERSION into a generated header,
<build dir>/generated/CrossPointVersion.h, and put that directory on the include path.

The default (dev) environment gets git branch and short SHA, e.g.
1.1.0-dev-feat-kosync-xpath-05c6cf8; every other environment uses VERSION plus its optional
custom_crosspoint_version_suffix from platformio.ini.

CrossMosa: this used to be a -D flag. A -D flag goes on every compile command,
so bumping the version (every internal build) or committing (default env)
recompiled all ~400 files (~9 min on the build host). Now only the files that
#include "CrossPointVersion.h" rebuild, and the header is rewritten only when
the string changes.
"""

import os
import subprocess
import sys


def warn(msg):
    print(f'WARNING [git_branch.py]: {msg}', file=sys.stderr)


def run_git_value(project_dir, args, label):
    try:
        value = subprocess.check_output(
            ['git', *args],
            text=True, stderr=subprocess.PIPE, cwd=project_dir
        ).strip()
        # Strip characters that would break a C string literal
        return ''.join(c for c in value if c not in '"\\')
    except FileNotFoundError:
        warn(f'git not found on PATH; {label} suffix will be "unknown"')
        return 'unknown'
    except subprocess.CalledProcessError as e:
        warn(
            f'git command failed (exit {e.returncode}): '
            f'{e.stderr.strip()}; {label} suffix will be "unknown"'
        )
        return 'unknown'
    except OSError as e:
        warn(
            f'OS error reading git {label}: {e}; '
            f'{label} suffix will be "unknown"'
        )
        return 'unknown'
    except Exception as e:  # pylint: disable=broad-exception-caught
        warn(
            f'Unexpected error reading git {label}: {e}; '
            f'{label} suffix will be "unknown"'
        )
        return 'unknown'


def get_git_branch(project_dir):
    branch = run_git_value(
        project_dir, ['rev-parse', '--abbrev-ref', 'HEAD'], 'branch'
    )
    # Detached HEAD has no branch name.
    if branch == 'HEAD':
        return 'detached'
    return branch


def get_git_short_sha(project_dir):
    return run_git_value(
        project_dir, ['rev-parse', '--short', 'HEAD'], 'short SHA'
    )


def get_base_version(project_dir):
    # CrossMosa: the version lives in VERSION, not platformio.ini. PlatformIO hashes
    # platformio.ini into .pio/build/project.checksum and wipes every env's build
    # directory when it changes, so a version there meant a full rebuild per release.
    path = os.path.join(project_dir, 'VERSION')
    try:
        with open(path, encoding='utf-8') as f:
            value = f.read().strip()
    except OSError:
        value = ''
    if not value:
        warn(f'{path} missing or empty; base version will be "0.0.0"')
        return '0.0.0'
    return ''.join(c for c in value if c not in '"\\')


def version_for(env):
    project_dir = env['PROJECT_DIR']
    base_version = get_base_version(project_dir)
    if env['PIOENV'] == 'default':
        branch = get_git_branch(project_dir)
        short_sha = get_git_short_sha(project_dir)
        return f'{base_version}-dev-{branch}-{short_sha}'
    suffix = env.GetProjectOption('custom_crosspoint_version_suffix', '')
    return base_version + ''.join(c for c in suffix if c not in '"\\')


def inject_version(env):
    version_string = version_for(env)
    out_dir = os.path.join(env.subst('$BUILD_DIR'), 'generated')
    os.makedirs(out_dir, exist_ok=True)
    header = os.path.join(out_dir, 'CrossPointVersion.h')
    text = (
        '#pragma once\n'
        '// Generated by scripts/git_branch.py; do not edit.\n'
        f'#define CROSSPOINT_VERSION "{version_string}"\n'
    )
    try:
        with open(header, encoding='utf-8') as f:
            current = f.read()
    except OSError:
        current = None
    if current != text:  # untouched mtime = no rebuild of the includers
        with open(header, 'w', encoding='utf-8') as f:
            f.write(text)
    env.Append(CPPPATH=[out_dir])
    print(f'CrossPoint build version: {version_string}')


# PlatformIO/SCons entry point — Import and env are SCons builtins injected at runtime.
# When run directly with Python (e.g. for validation), a lightweight fake env is used
# so the git/version logic can be exercised without a full build.
try:
    Import('env')           # noqa: F821  # type: ignore[name-defined]
    inject_version(env)     # noqa: F821  # type: ignore[name-defined]
except NameError:
    _project_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    print(version_for({'PIOENV': 'default', 'PROJECT_DIR': _project_dir}))
