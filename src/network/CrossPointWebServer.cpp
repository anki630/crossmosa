void CrossPointWebServer::handleFileListData() const {
  // Get current path from query string (default to root)
  String currentPath = "/";
  if (server->hasArg("path") && !canonicalWebPath(server->arg("path"), currentPath)) {
    server->send(400, "text/plain", "Invalid path");
    return;
  }
  // v361（codex）：受保護的位置不能列 —— 以前直接給 path=/.crossmosa 就能列出設定、WiFi 這些檔的名字與大小。
  //   唯一的例外是資料目錄本身，而且只列兩份診斷 log：這台機器沒有序列埠，「開顯示隱藏檔、點進資料目錄、
  //   下載 log」是唯一拿得到 log 的路（下載端的例外也只放行這兩份，見 handleDownload）。
  //   用字面比對資料目錄：8.3 別名（CROSSM~1）、大小寫以外的任何變形都落到 403。
  bool diagnosticsOnly = false;
  if (isProtectedItemPath(currentPath)) {
    if (strcasecmp(currentPath.c_str(), DataDir::path()) != 0) {
      server->send(403, "text/plain", "Cannot access protected items");
      return;
    }
    diagnosticsOnly = true;
  }

  server->setContentLength(CONTENT_LENGTH_UNKNOWN);
  server->send(200, "application/json", "");
  server->sendContent("[");
  char output[512];
  constexpr size_t outputSize = sizeof(output);
  bool seenFirst = false;
  JsonDocument doc;

  scanFiles(currentPath.c_str(),
            [this, &output, &doc, seenFirst, diagnosticsOnly, &currentPath](const FileInfo& info) mutable {
              if (diagnosticsOnly && !DiagLog::isDiagnosticPath((currentPath + "/" + info.name).c_str())) return;
              doc.clear();
              doc["name"] = info.name;
              doc["size"] = info.size;
              doc["isDirectory"] = info.isDirectory;
              doc["isEpub"] = info.isEpub;

              const size_t written = serializeJson(doc, output, outputSize);
              if (written >= outputSize) {
                // JSON output truncated; skip this entry to avoid sending malformed JSON
                LOG_DBG("WEB", "Skipping file entry with oversized JSON for name: %s", info.name.c_str());
                return;
              }

              if (seenFirst) {
                server->sendContent(",");
              } else {
                seenFirst = true;
              }
              server->sendContent(output);
            });
  server->sendContent("]");
  // End of streamed response, empty chunk to signal client
  server->sendContent("");
  LOG_DBG("WEB", "Served file listing page for path: %s", currentPath.c_str());
}

void CrossPointWebServer::handleDownload() const {
  if (!server->hasArg("path")) {
    server->send(400, "text/plain", "Missing path");
    return;
  }

  String itemPath;
  if (!canonicalWebPath(server->arg("path"), itemPath) || itemPath == "/") {
    server->send(400, "text/plain", "Invalid path");
    return;
  }

  // v79：兩份診斷 log 是【唯一】的例外，而且先檢查，所以這個例外只可能是整條路徑的精確相符。
  //
  // 這台裝置沒有序列埠，diag.log 是唯一的遙測管道 —— 而它就住在受保護的資料目錄裡。
  // v135 的逐段守衛（正確地）擋掉了 /.crosspoint 底下的一切，也順手把 log 一起擋掉了。
  // 兩個檔都不含任何憑證。設計上 fail-closed：它只可能放行這兩個特定檔名，
  // 8.3 別名、前導空白、資料目錄裡的任何其他檔都走不過去。見 DiagLog::isDiagnosticPath()。
  const bool isDiagnostics = DiagLog::isDiagnosticPath(itemPath.c_str());

  // ⚠️ 逐段，不是只看最後一段 —— /.crosspoint/wifi.json 的最後一段是 wifi.json。
  if (!isDiagnostics && isProtectedItemPath(itemPath)) {
    server->send(403, "text/plain", "Cannot access protected items");
    return;
  }

  if (!Storage.exists(itemPath.c_str())) {
    server->send(404, "text/plain", "Item not found");
    return;
  }

  HalFile file = Storage.open(itemPath.c_str());
  if (!file) {
    server->send(500, "text/plain", "Failed to open file");
    return;
  }
  if (file.isDirectory()) {
    file.close();
    server->send(400, "text/plain", "Path is a directory");
    return;
  }

  String contentType = "application/octet-stream";
  if (isEpubFile(itemPath)) {
    contentType = "application/epub+zip";
  }

  char nameBuf[128] = {0};
  String filename = "download";
  if (file.getName(nameBuf, sizeof(nameBuf))) {
    filename = nameBuf;
  }

  server->setContentLength(file.size());
  server->sendHeader("Content-Disposition", "attachment; filename=\"" + filename + "\"");
  server->send(200, contentType.c_str(), "");

  NetworkClient client = server->client();
  const size_t chunkSize = 4096;
  uint8_t buffer[chunkSize];

  bool downloadOk = true;
  while (downloadOk && file.available()) {
    int result = file.read(buffer, chunkSize);
    if (result <= 0) break;
    size_t bytesRead = static_cast<size_t>(result);
    size_t totalWritten = 0;
    while (totalWritten < bytesRead) {
      resetTaskWatchdogIfSubscribed();
      size_t wrote = client.write(buffer + totalWritten, bytesRead - totalWritten);
      if (wrote == 0) {
        downloadOk = false;
        break;
      }
      totalWritten += wrote;
    }
  }
  client.clear();
  file.close();
}

// Diagnostic counters for upload performance analysis
static unsigned long uploadStartTime = 0;
static unsigned long totalWriteTime = 0;
static size_t writeCount = 0;

static bool flushUploadBuffer(CrossPointWebServer::UploadState& state) {
  if (state.bufferPos > 0 && state.file) {
    resetTaskWatchdogIfSubscribed();  // Reset watchdog before potentially slow SD write
    const unsigned long writeStart = millis();
    const size_t written = state.file.write(state.buffer.data(), state.bufferPos);
    totalWriteTime += millis() - writeStart;
    writeCount++;
    resetTaskWatchdogIfSubscribed();  // Reset watchdog after SD write

    if (written != state.bufferPos) {
      LOG_DBG("WEB", "[UPLOAD] Buffer flush failed: expected %d, wrote %d", state.bufferPos, written);
      state.bufferPos = 0;
      return false;
    }
    state.bufferPos = 0;
  }
  return true;
}

void CrossPointWebServer::handleUpload(UploadState& state) const {
  static size_t lastLoggedSize = 0;

  // Reset watchdog at start of every upload callback - HTTP parsing can be slow
  resetTaskWatchdogIfSubscribed();

  // Safety check: ensure server is still valid
  if (!running || !server) {
    LOG_DBG("WEB", "[UPLOAD] ERROR: handleUpload called but server not running!");
    return;
  }

  const HTTPUpload& upload = server->upload();

  if (upload.status == UPLOAD_FILE_START) {
    // Reset watchdog - this is the critical 1% crash point
    resetTaskWatchdogIfSubscribed();

    state.fileName = upload.filename;
    state.size = 0;
    state.success = false;
    state.error = "";
    uploadStartTime = millis();
    lastLoggedSize = 0;
    state.bufferPos = 0;
    totalWriteTime = 0;
    writeCount = 0;
    DiagLog::line("WEBUP start %s", upload.filename.c_str());  // v178：上傳當機的麵包屑

    // v361：檔名只能是一段（"sub/x.epub" 不能借上傳寫進別的資料夾）。
    // 拒絕時不開檔 —— 之後的 WRITE／END／ABORTED 都看 state.file，不會動到任何檔。
    switch (checkUserName(state.fileName)) {
      case NameCheck::Ok:
        break;
      case NameCheck::Protected:
        state.error = "Cannot write to protected location";
        return;
      default:
        state.error = "Invalid file name";
        return;
    }

    // Get upload path from query parameter (defaults to root if not specified)
    // Note: We use query parameter instead of form data because multipart form
    // fields aren't available until after file upload completes
    state.path = "/";
    if (server->hasArg("path") && !canonicalWebPath(server->arg("path"), state.path)) {
      state.error = "Invalid path";
      return;
    }

    LOG_DBG("WEB", "[UPLOAD] START: %s to path: %s", state.fileName.c_str(), state.path.c_str());
    LOG_DBG("WEB", "[UPLOAD] Free heap: %d bytes", ESP.getFreeHeap());

    String filePath = state.path;
    if (!filePath.endsWith("/")) filePath += "/";
    filePath += state.fileName;

    // v77：上傳完全沒有守衛 —— 同網段任何人都能往 /.crosspoint/ 寫檔，
    // 覆蓋 settings.json、wifi.json、或塞一個假的 book.bin。
    // 逐段檢查【完整目標路徑】（不是只看檔名，也不是只看目錄）。
    // v361（codex）：放在 exists() 之前 —— 反過來的話，「名稱衝突」與「受保護」兩種回覆可以拿來探測資料目錄裡有哪些檔。
    if (isProtectedItemPath(filePath)) {
      state.error = "Cannot write to protected location";
      LOG_ERR("WEB", "[UPLOAD] refused protected path: %s", filePath.c_str());
      return;
    }

    // Check if file already exists - SD operations can be slow
    resetTaskWatchdogIfSubscribed();
    if (Storage.exists(filePath.c_str())) {
      state.error = "File already exists: " + state.fileName;
      LOG_DBG("WEB", "[UPLOAD] Collision: %s", filePath.c_str());
      return;
    }

    // Open file for writing - this can be slow due to FAT cluster allocation
    resetTaskWatchdogIfSubscribed();

    if (!Storage.openFileForWrite("WEB", filePath, state.file)) {
      state.error = "Failed to create file on SD card";
      LOG_DBG("WEB", "[UPLOAD] FAILED to create file: %s", filePath.c_str());
      return;
    }
    resetTaskWatchdogIfSubscribed();

    LOG_DBG("WEB", "[UPLOAD] File created successfully: %s", filePath.c_str());
  } else if (upload.status == UPLOAD_FILE_WRITE) {
    if (state.file && state.error.isEmpty()) {
      // Buffer incoming data and flush when buffer is full
      // This reduces SD card write operations and improves throughput
      const uint8_t* data = upload.buf;
      size_t remaining = upload.currentSize;

      while (remaining > 0) {
        const size_t space = UploadState::UPLOAD_BUFFER_SIZE - state.bufferPos;
        const size_t toCopy = (remaining < space) ? remaining : space;

        memcpy(state.buffer.data() + state.bufferPos, data, toCopy);
        state.bufferPos += toCopy;
        data += toCopy;
        remaining -= toCopy;

        // Flush buffer when full
        if (state.bufferPos >= UploadState::UPLOAD_BUFFER_SIZE) {
          if (!flushUploadBuffer(state)) {
            state.error = "Failed to write to SD card - disk may be full";
            state.file.close();
            return;
          }
        }
      }

      state.size += upload.currentSize;

      // Log progress every 100KB
      if (state.size - lastLoggedSize >= 102400) {
        const unsigned long elapsed = millis() - uploadStartTime;
        const float kbps = (elapsed > 0) ? (state.size / 1024.0) / (elapsed / 1000.0) : 0;
        LOG_DBG("WEB", "[UPLOAD] %d bytes (%.1f KB), %.1f KB/s, %d writes", state.size, state.size / 1024.0, kbps,
                writeCount);
        lastLoggedSize = state.size;
      }
    }
  } else if (upload.status == UPLOAD_FILE_END) {
    if (state.file) {
      // Flush any remaining buffered data
      if (!flushUploadBuffer(state)) {
        state.error = "Failed to write final data to SD card";
      }
      state.file.close();
      DiagLog::line("WEBUP end bytes=%u err=%s", static_cast<unsigned>(state.size), state.error.c_str());

      if (state.error.isEmpty()) {
        state.success = true;
        const unsigned long elapsed = millis() - uploadStartTime;
        const float avgKbps = (elapsed > 0) ? (state.size / 1024.0) / (elapsed / 1000.0) : 0;
        const float writePercent = (elapsed > 0) ? (totalWriteTime * 100.0 / elapsed) : 0;
        LOG_DBG("WEB", "[UPLOAD] Complete: %s (%d bytes in %lu ms, avg %.1f KB/s)", state.fileName.c_str(), state.size,
                elapsed, avgKbps);
        LOG_DBG("WEB", "[UPLOAD] Diagnostics: %d writes, total write time: %lu ms (%.1f%%)", writeCount, totalWriteTime,
                writePercent);

        // Clear epub cache after uploading the file
        String filePath = state.path;
        if (!filePath.endsWith("/")) filePath += "/";
        filePath += state.fileName;
        clearBookCache(filePath.c_str());
      }
    }
  } else if (upload.status == UPLOAD_FILE_ABORTED) {
    state.bufferPos = 0;  // Discard buffered data
    if (state.file) {
      state.file.close();
      // Try to delete the incomplete file
      String filePath = state.path;
      if (!filePath.endsWith("/")) filePath += "/";
      filePath += state.fileName;
      Storage.remove(filePath.c_str());
    }
    state.error = "Upload aborted";
    LOG_DBG("WEB", "Upload aborted");
  }
}

